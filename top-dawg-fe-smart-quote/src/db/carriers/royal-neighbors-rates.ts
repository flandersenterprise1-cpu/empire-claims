/**
 * Royal Neighbors of America -- Ensured Legacy Final Expense rates.
 *
 * Source: rate sheet 2996-1-R Rev. 2-2025, "Final Expense 2025 Premiums Per
 * 1000". Annual premium per $1,000 of face, by issue age, sex and tobacco
 * class, for all four rate classes the sheet prints.
 *
 * The sheet also prints the modal factors and the exact order of operations,
 * which is not the usual one -- the per-$1,000 rate is converted to the mode
 * and rounded BEFORE it is multiplied by units, and the modal certificate fee
 * is added after:
 *
 *   [ (rate x modal factor) rounded to 2 places x units ] rounded to 2 places
 *     + modal certificate fee = modal premium
 *
 * Its own worked example, male 60 SIWL Standard non-tobacco at $10,000:
 *   (53.75 x 0.087) = 4.68 -> 4.68 x 10 = 46.80 -> + 4.35 = $51.15 monthly.
 *
 * Rounding in that order matters: 53.75 x 0.087 x 10 + 4.35 computed straight
 * through is $51.11, four cents under what the carrier bills.
 */

